/**
 * The output an event is written as (ADR-0056): its own name, or for a native DOM event's name
 * `uf` and the name in PascalCase (`change` → `ufChange`), which the native event bubbling out
 * of the component through its host cannot reach.
 */
export function outputName(event: string): string {
  return NATIVE_EVENTS.has(event) ? `uf${event.charAt(0).toUpperCase()}${event.slice(1)}` : event;
}
