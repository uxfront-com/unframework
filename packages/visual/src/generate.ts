// The story generator: a list of stories in, the stories files a Storybook reads out. One file per
// title, so each case is a lazy chunk of its own (Storybook imports a stories file on demand), and
// one more for the hidden runner story. A story's id is written down rather than left to
// Storybook's rule (`startCase` splits `a1` into `a-1`), so ids are the same on every target.
import { posix } from "node:path";

/** One story of a catalogue. */
export interface Story {
  /** `<area>-<name>--<scenario>`, the same on every target. */
  id: string;
  /** The sidebar's path, `<area>/<name>`: the stories of a title share a file. */
  title: string;
  /** The component's `.uf.tsx` file, absolute. */
  source: string;
  /** The props, as JavaScript: an object literal, which may hold `undefined`. */
  args: string;
  /**
   * Why the target has no output for the story's case: the story shows it as text, and imports
   * no component, since a stand-in throws when rendered (ADR-0068).
   */
  noOutput?: string;
}

/** The hidden story the specs run in. It renders nothing, and is no part of a list of stories. */
export const RUNNER_STORY = "uf-runner--spec";

/** The global the runner story's module sets: what a driver calls to run one spec file. */
export const RUN_SPEC = "__ufRunSpec";

/** One file to write under the directory the stories live in. */
export interface GeneratedFile {
  /** Its name in that directory. */
  file: string;
  contents: string;
}

const HEADER = "// Generated by @unframework/visual: edits are overwritten.";

/** The file a title's stories live in: `state/counter` is `state-counter.stories.ts`. */
function fileOf(title: string): string {
  return `${title.replaceAll("/", "-")}.stories.ts`;
}

/** A path as an import from a file in `directory` writes it. */
function importPath(directory: string, file: string): string {
  const path = posix.relative(directory, file);
  return path.startsWith(".") ? path : `./${path}`;
}

/** A story's name, in the sidebar: its scenario, which its id ends with. */
function nameOf(id: string): string {
  return id.slice(id.indexOf("--") + 2);
}

/** A title's stories file. A case without output on the target imports nothing. */
function storiesFile(directory: string, title: string, stories: readonly Story[]): string {
  const [first] = stories;
  const component = first?.noOutput === undefined;
  const lines = [HEADER];
  if (component)
    lines.push(`import Component from ${JSON.stringify(importPath(directory, first!.source))};`);
  lines.push(
    "",
    `export default { title: ${JSON.stringify(title)}${component ? ", component: Component" : ""} };`,
  );
  for (const [index, story] of stories.entries()) {
    const parameters = [
      `__id: ${JSON.stringify(story.id)}`,
      ...(story.noOutput === undefined ? [] : [`ufNoOutput: ${JSON.stringify(story.noOutput)}`]),
    ];
    lines.push(
      "",
      `export const Story${index} = {`,
      `  name: ${JSON.stringify(nameOf(story.id))},`,
      `  args: ${story.args},`,
      `  parameters: { ${parameters.join(", ")} },`,
      "};",
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * The stories files of a list. Throws on a title whose stories disagree on their component, which
 * one file cannot hold, and on an id two stories share.
 */
export function generateStories(directory: string, stories: readonly Story[]): GeneratedFile[] {
  const ids = new Set<string>();
  const titles = new Map<string, Story[]>();
  for (const story of stories) {
    if (ids.has(story.id)) throw new Error(`Two stories have the id ${story.id}.`);
    ids.add(story.id);
    const siblings = titles.get(story.title);
    if (siblings) siblings.push(story);
    else titles.set(story.title, [story]);
  }
  return [...titles].map(([title, siblings]) => {
    const other = siblings.find(
      (story) => story.source !== siblings[0]!.source || story.noOutput !== siblings[0]!.noOutput,
    );
    if (other) {
      throw new Error(
        `${title}'s stories render different components: ${siblings[0]!.id} and ${other.id}. A title has one component.`,
      );
    }
    return { file: fileOf(title), contents: storiesFile(directory, title, siblings) };
  });
}

/** What a runner story's module needs. */
export interface RunnerOptions {
  /** The target's name, whose adapter the specs mount with. */
  target: string;
  /** Every spec file, absolute: each is a lazy chunk the catalogue never loads. */
  specs: readonly string[];
}

/**
 * The runner story's file. Hidden from the sidebar and rendering nothing, it is the document the
 * specs run in: its module holds the only imports of the page host and of the specs, each dynamic,
 * so a page that browses the catalogue loads none of them.
 */
export function generateRunner(directory: string, options: RunnerOptions): GeneratedFile {
  const specs = options.specs.map(
    (spec) =>
      `  ${JSON.stringify(spec)}: () => import(${JSON.stringify(importPath(directory, spec))}),`,
  );
  const lines = [
    HEADER,
    "",
    'export default { title: "uf-runner", tags: ["!dev", "!autodocs", "!test"] };',
    "",
    `export const Spec = { name: "spec", parameters: { __id: ${JSON.stringify(RUNNER_STORY)}, ufRunner: true } };`,
    "",
    "const specs = {",
    ...specs,
    "};",
    "",
    `globalThis.${RUN_SPEC} = async (filepath) => {`,
    "  const load = specs[filepath];",
    "  if (!load) throw new Error(`This build holds no spec ${filepath}.`);",
    '  await import("@unframework/testing/hosts/page");',
    '  await import("@unframework/testing/setup");',
    `  await import(${JSON.stringify(`@unframework/testing/${options.target}`)});`,
    '  const { runSpecFile } = await import("@unframework/testing/hosts/page/run");',
    "  return runSpecFile({ filepath, load });",
    "};",
  ];
  return { file: "uf-runner.stories.ts", contents: `${lines.join("\n")}\n` };
}
