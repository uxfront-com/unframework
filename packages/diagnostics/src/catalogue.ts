/** Every catalogued diagnostic, by code. */
export const catalogue: ReadonlyMap<DiagnosticCode, CatalogueEntry> = new Map(
  entries.map((entry) => [entry.code, entry]),
);

/** Looks up a code's documentation. */
export function lookup(code: string): CatalogueEntry | undefined {
  return catalogue.get(code as DiagnosticCode);
}

/** The documentation URL of a code. */
export function docsUrl(code: DiagnosticCode): string {
  return `https://unframework.dev/diagnostics/${code}`;
}
